import { readFileSync, writeFileSync } from 'node:fs';

// A deterministic, offline mapping. Source colors and provenance live in the JSON;
// contrast adjustments are recorded so they never silently replace source values.
const palettes = JSON.parse(readFileSync(new URL('../src/theme-palettes.json', import.meta.url)));
const adjustments = {};
const rgb = (hex) =>
  hex
    .slice(1)
    .match(/../g)
    .map((v) => parseInt(v, 16));
const hex = (channels) =>
  '#' + channels.map((v) => Math.round(v).toString(16).padStart(2, '0')).join('');
const luminance = (color) =>
  rgb(color)
    .map((v) => v / 255)
    .map((v) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4))
    .reduce((n, v, i) => n + v * [0.2126, 0.7152, 0.0722][i], 0);
const contrast = (a, b) =>
  (Math.max(luminance(a), luminance(b)) + 0.05) / (Math.min(luminance(a), luminance(b)) + 0.05);
function resolve(id, mode) {
  const palette = palettes[id][mode];
  if (!palette || Object.keys(palettes.procode.dark).some((key) => !(key in palette))) {
    throw new Error(`Incomplete palette: ${id}/${mode}`);
  }
  const t = { ...palette };
  const changes = {};
  const adjust = (key, backgrounds, minimum = 4.5) => {
    const original = t[key];
    if (!/^#[a-f\d]{6}$/i.test(original))
      throw new Error(`Invalid color ${id}/${key}: ${original}`);
    const bg = backgrounds.map((key) => t[key]);
    const passes = (color) => bg.every((background) => contrast(color, background) >= minimum);
    if (passes(original)) return;
    const target = mode === 'light' ? 0 : 255;
    for (let step = 1; step <= 100; step++) {
      const candidate = hex(rgb(original).map((c) => c + ((target - c) * step) / 100));
      if (passes(candidate)) {
        t[key] = candidate;
        changes[key] = { source: original, applied: candidate, minimum, backgrounds };
        return;
      }
    }
    throw new Error(`Cannot achieve contrast for ${id}/${mode}/${key}`);
  };
  const surfaces = ['bg', 'sidebar', 'panel', 'surface', 'hover', 'inset'];
  for (const key of ['text', 'secondary', 'muted']) adjust(key, surfaces);
  adjust('accent', [...surfaces, 'accent-soft']);
  adjust('editor-text', ['inset', 'editor-line', 'selection']);
  for (const key of Object.keys(t).filter(
    (k) => k.startsWith('syntax-') && k !== 'syntax-comment-style',
  ))
    adjust(key, ['inset', 'editor-line', 'selection']);
  for (const key of ['warning', 'error', 'success']) adjust(key, [`${key}-bg`]);
  adjust('border-strong', ['panel', 'surface'], 3);
  adjust('accent-border', ['panel', 'accent-soft'], 3);
  if (contrast(t['accent-ink'], t['accent-fill']) < 4.5) {
    const source = t['accent-ink'];
    t['accent-ink'] = contrast('#ffffff', t['accent-fill']) >= 4.5 ? '#ffffff' : '#000000';
    changes['accent-ink'] = {
      source,
      applied: t['accent-ink'],
      minimum: 4.5,
      backgrounds: ['accent-fill'],
    };
  }
  if (Object.keys(changes).length) adjustments[`${id}/${mode}`] = changes;
  return t;
}
const block = (t) =>
  Object.entries(t)
    .map(([key, value]) => `  --${key}: ${value};`)
    .join('\n');
let css =
  '/* Generated by scripts/generate-themes.mjs. Edit theme-palettes.json.\n * Sources and intentional adaptations: docs/THEMES.md. */\n';
css += `:root {\n  color-scheme: dark;\n${block(resolve('procode', 'dark'))}\n}\n`;
for (const mode of ['light', 'dark', 'midnight']) {
  css += `:root[data-mode='${mode}'] { color-scheme: ${mode === 'light' ? 'light' : 'dark'}; }\n`;
}
for (const [id, palette] of Object.entries(palettes)) {
  css += `/* ${palette.name}: ${palette.source} */\n`;
  for (const mode of ['light', 'dark', 'midnight']) {
    css += `:root[data-theme='${id}'][data-mode='${mode}'],\n:root[data-mode='${mode}'] .theme-swatch[data-theme='${id}'] {\n${block(resolve(id, mode))}\n}\n`;
  }
}
writeFileSync(new URL('../src/themes.css', import.meta.url), css);
writeFileSync(
  new URL('../docs/theme-contrast-adjustments.json', import.meta.url),
  JSON.stringify(adjustments, null, 2) + '\n',
);
console.log(
  `Prepared ${Object.keys(palettes).length * 3} local theme variants with contrast-checked color tokens.`,
);
