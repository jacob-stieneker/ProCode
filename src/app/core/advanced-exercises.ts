import type { Exercise, Difficulty } from './exercises';
type Case = [string, unknown[], unknown];
function exercise(
  id: string,
  title: string,
  difficulty: Difficulty,
  category: string,
  names: [string, string],
  params: string,
  initial: string,
  description: string,
  requirements: string[],
  hints: [string, string, string],
  explanation: string,
  cases: Case[],
): Exercise {
  const checks = cases.map(([name, input, expected]) => ({
    name,
    input,
    expected,
    hint: hints[1],
  }));
  return {
    id,
    title,
    difficulty,
    area: ['daily-temperatures', 'tree-level-order', 'tree-max-path'].includes(id)
      ? 'data-structures'
      : 'algorithms',
    category,
    version: 1,
    minutes: difficulty === 'skilled' ? '20–30 min' : '30–45 min',
    description,
    requirements,
    hints,
    explanation,
    signature: { javascript: names[0], python: names[1] },
    starter: {
      javascript: `function ${names[0]}(${params}) {\n  // Write your solution here.\n  return ${initial};\n}\n`,
      python: `def ${names[1]}(${params}):\n    # Write your solution here.\n    return ${initial}\n`,
    },
    examples: checks.slice(0, 3),
    additional: checks.slice(3),
  };
}
