import type { Check, Exercise } from './exercises';

type Case = [name: string, input: unknown[], expected: unknown];
function foundation(config: {
  id: string;
  title: string;
  category: string;
  minutes?: string;
  description: string;
  requirements: string[];
  signatures: [string, string];
  params: string;
  initial: [string, string];
  hints: [string, string, string];
  explanation: string;
  cases: Case[];
}): Exercise {
  const checks: Check[] = config.cases.map(([name, input, expected]) => ({
    name,
    input,
    expected,
    hint: config.hints[1],
  }));
  return {
    id: config.id,
    version: 1,
    difficulty: 'junior',
    area: config.id === 'valid-parentheses' ? 'data-structures' : 'algorithms',
    title: config.title,
    category: config.category,
    minutes: config.minutes ?? '10–20 min',
    description: config.description,
    requirements: config.requirements,
    signature: { javascript: config.signatures[0], python: config.signatures[1] },
    starter: {
      javascript: `function ${config.signatures[0]}(${config.params}) {\n  // Write your solution here.\n  \n  return ${config.initial[0]};\n}\n`,
      python: `def ${config.signatures[1]}(${config.params}):\n    # Write your solution here.\n\n    return ${config.initial[1]}\n`,
    },
    hints: config.hints,
    explanation: config.explanation,
    examples: checks.slice(0, 3),
    additional: checks.slice(3),
  };
}
